SELECT CAR_ID, c.CAR_TYPE, DAILY_FEE * (100 - DISCOUNT_RATE) / 100 * 30 AS FEE
FROM CAR_RENTAL_COMPANY_CAR c
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN p ON c.CAR_TYPE = p.CAR_TYPE
WHERE DURATION_TYPE = '30일 이상'
    AND c.CAR_TYPE IN ('세단', 'SUV')
    AND CAR_ID NOT IN (SELECT CAR_ID FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY WHERE START_DATE <= '2022-11-30' AND END_DATE >= '2022-11-01')  # 대여 불가능 서브쿼리
    AND 500000 <= (DAILY_FEE * (100 - DISCOUNT_RATE) / 100) * 30 AND (DAILY_FEE * (100 - DISCOUNT_RATE) / 100) * 30 < 2000000
ORDER BY FEE DESC, CAR_TYPE ASC, CAR_ID DESC;
