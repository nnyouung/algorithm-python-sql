SELECT GRADE, ID, EMAIL
FROM (SELECT ID, EMAIL,
     CASE WHEN SUM(CATEGORY = 'Front End') > 0 AND SUM(NAME = 'Python') > 0 THEN 'A'
      WHEN SUM(NAME = 'C#') > 0 THEN 'B'
      WHEN SUM(CATEGORY = 'Front End') > 0 THEN 'C'
      END AS GRADE
     FROM DEVELOPERS JOIN SKILLCODES ON SKILL_CODE & CODE != 0
     GROUP BY ID) n
WHERE GRADE IS NOT NULL
ORDER BY GRADE, ID;
